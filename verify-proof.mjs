import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const p = JSON.parse(fs.readFileSync('pi-proof.json', 'utf8'));
assert(p.streamed > 0, 'No streamed text');
assert(p.answer.includes('STEERING_CONFIRMED'), 'Steering not delivered');
assert(p.handback?.answer, 'The worker did not hand back with finish');
for (const tool of ['web_search', 'read_page', 'write']) assert(p.events.some(e => e.type === 'tool_execution_end' && e.toolName === tool && !e.isError), `${tool} did not succeed`);
assert(p.events.some(e => e.type === 'tool_execution_end' && /powershell|bash/.test(e.toolName) && !e.isError), 'The shell did not run');
assert(p.events.some(e => e.type === 'tool_execution_end' && e.isError && JSON.stringify(e.result).includes('aborted')), 'No aborted tool evidence');
assert(fs.existsSync(p.sessionFile), 'Pi session not persisted');
assert(fs.readFileSync(path.join(p.outDir, 'proof.txt'), 'utf8').includes('https://'), 'Output has no source');
console.log('PASS: real streaming, search, extraction, file, execution, steering, hand-back, cancellation and Pi persistence');
